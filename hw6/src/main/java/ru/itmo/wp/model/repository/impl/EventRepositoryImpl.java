package ru.itmo.wp.model.repository.impl;

import ru.itmo.wp.model.database.DatabaseUtils;
import ru.itmo.wp.model.domain.Event;
import ru.itmo.wp.model.exception.RepositoryException;
import ru.itmo.wp.model.repository.EventRepository;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

public class EventRepositoryImpl implements EventRepository {
    private final DataSource dataSource = DatabaseUtils.getDataSource();

    @Override
    public void save(Event event) {
        try (Connection connection = dataSource.getConnection();
             PreparedStatement statement = connection.prepareStatement(
                     "INSERT INTO `Event` (`userId`, `type`, `creationTime`) VALUES (?, ?, ?)",
                     Statement.RETURN_GENERATED_KEYS)) {
            statement.setLong(1, event.getUserId());
            statement.setString(2, event.getType().name());
            statement.setTimestamp(3, event.getCreationTime());
            if (statement.executeUpdate() != 1) {
                throw new RepositoryException("Can't save Event.");
            }
            try (ResultSet keys = statement.getGeneratedKeys()) {
                if (keys.next()) {
                    event.setId(keys.getLong(1));
                } else {
                    throw new RepositoryException("Can't save Event [no autogenerated id].");
                }
            }
        } catch (SQLException e) {
            throw new RepositoryException("Can't save Event.", e);
        }
    }
}
