package ru.itmo.wp.model.repository.impl;

import ru.itmo.wp.model.database.DatabaseUtils;
import ru.itmo.wp.model.domain.Article;
import ru.itmo.wp.model.exception.RepositoryException;
import ru.itmo.wp.model.repository.ArticleRepository;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;

public class ArticleRepositoryImpl implements ArticleRepository {
    private final DataSource dataSource = DatabaseUtils.getDataSource();

    @Override
    public void save(Article article) {
        try (Connection connection = dataSource.getConnection();
             PreparedStatement statement = connection.prepareStatement(
                     "INSERT INTO `Article` (`userId`, `title`, `text`, `creationTime`) VALUES (?, ?, ?, ?)",
                     Statement.RETURN_GENERATED_KEYS)) {
            statement.setLong(1, article.getUserId());
            statement.setString(2, article.getTitle());
            statement.setString(3, article.getText());
            statement.setTimestamp(4, article.getCreationTime());
            if (statement.executeUpdate() != 1) {
                throw new RepositoryException("Can't save Article.");
            }
            try (ResultSet keys = statement.getGeneratedKeys()) {
                if (keys.next()) {
                    article.setId(keys.getLong(1));
                } else {
                    throw new RepositoryException("Can't save Article [no autogenerated id].");
                }
            }
        } catch (SQLException e) {
            throw new RepositoryException("Can't save Article.", e);
        }
    }

    @Override
    public Article find(long id) {
        String sql = "SELECT `id`, `userId`, `title`, `text`, `hidden`, `creationTime` "
                + "FROM `Article` WHERE `id` = ?";
        try (Connection connection = dataSource.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setLong(1, id);
            try (ResultSet resultSet = statement.executeQuery()) {
                return resultSet.next() ? toArticle(resultSet) : null;
            }
        } catch (SQLException e) {
            throw new RepositoryException("Can't find Article.", e);
        }
    }

    @Override
    public List<Article> findAllVisible() {
        List<Article> articles = new ArrayList<>();
        String sql = "SELECT a.`id`, a.`userId`, a.`title`, a.`text`, a.`hidden`, a.`creationTime`, "
                + "u.`login` AS `authorLogin` "
                + "FROM `Article` a JOIN `User` u ON u.`id` = a.`userId` "
                + "WHERE a.`hidden` = FALSE "
                + "ORDER BY a.`creationTime` DESC, a.`id` DESC";
        try (Connection connection = dataSource.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql);
             ResultSet resultSet = statement.executeQuery()) {
            while (resultSet.next()) {
                Article article = toArticle(resultSet);
                article.setAuthorLogin(resultSet.getString("authorLogin"));
                articles.add(article);
            }
        } catch (SQLException e) {
            throw new RepositoryException("Can't find Articles.", e);
        }
        return articles;
    }

    @Override
    public List<Article> findByUserId(long userId) {
        List<Article> articles = new ArrayList<>();
        String sql = "SELECT `id`, `userId`, `title`, `text`, `hidden`, `creationTime` "
                + "FROM `Article` WHERE `userId` = ? ORDER BY `creationTime`, `id`";
        try (Connection connection = dataSource.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setLong(1, userId);
            try (ResultSet resultSet = statement.executeQuery()) {
                while (resultSet.next()) {
                    articles.add(toArticle(resultSet));
                }
            }
        } catch (SQLException e) {
            throw new RepositoryException("Can't find Articles.", e);
        }
        return articles;
    }

    @Override
    public void setHidden(long articleId, long userId, boolean hidden) {
        String sql = "UPDATE `Article` SET `hidden` = ? WHERE `id` = ? AND `userId` = ?";
        try (Connection connection = dataSource.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setBoolean(1, hidden);
            statement.setLong(2, articleId);
            statement.setLong(3, userId);
            statement.executeUpdate();
        } catch (SQLException e) {
            throw new RepositoryException("Can't update Article.", e);
        }
    }

    private Article toArticle(ResultSet resultSet) throws SQLException {
        Article article = new Article();
        article.setId(resultSet.getLong("id"));
        article.setUserId(resultSet.getLong("userId"));
        article.setTitle(resultSet.getString("title"));
        article.setText(resultSet.getString("text"));
        article.setHidden(resultSet.getBoolean("hidden"));
        article.setCreationTime(resultSet.getTimestamp("creationTime"));
        return article;
    }
}
